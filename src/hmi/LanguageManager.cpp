LanguageManager::LanguageManager(QObject* parent)
    : QObject(parent) {
    QSettings settings(QStringLiteral("SolarPowerhouse"), QStringLiteral("SolarPowerhouseHMI"));
    const QString storedLanguage = settings.value(QStringLiteral("language"), QStringLiteral("de")).toString();
    language_ = storedLanguage == QStringLiteral("en") ? QStringLiteral("en") : QStringLiteral("de");
}

QString LanguageManager::language() const {
    return language_;
}

void LanguageManager::setLanguage(const QString& language) {
    const QString normalized = language.toLower() == QStringLiteral("en") ? QStringLiteral("en") : QStringLiteral("de");
    if (language_ == normalized) return;

    language_ = normalized;
    QSettings settings(QStringLiteral("SolarPowerhouse"), QStringLiteral("SolarPowerhouseHMI"));
    settings.setValue(QStringLiteral("language"), language_);
    emit languageChanged();
}

QString LanguageManager::dateTimeFormat() const {
    return language_ == QStringLiteral("de") ? QStringLiteral("dd.MM.yyyy hh:mm") : QStringLiteral("yyyy-MM-dd hh:mm");
}

QString LanguageManager::text(const QString& key) const {
    const TranslationTable& table = language_ == QStringLiteral("de") ? germanTranslations() : englishTranslations();
    const auto iterator = table.constFind(key);
    if (iterator != table.constEnd()) return iterator.value();

    const TranslationTable& fallback = englishTranslations();
    const auto fallbackIterator = fallback.constFind(key);
    return fallbackIterator == fallback.constEnd() ? key : fallbackIterator.value();
}

